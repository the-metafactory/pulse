import type { ActionContext } from "../../../src/types/action";

interface OperatorAction {
  command: string;
  reason: string;
  priority: "high" | "normal" | "low";
  repo: string;
}

interface Input {
  summary: string;
  highlights: string[];
  blockers: string[];
  nextUp?: string[];
  operatorActions?: OperatorAction[];
  since?: string;
  org?: string;
  [key: string]: unknown;
}

export default {
  async execute(input: Input, ctx: ActionContext) {
    const { summary, highlights, blockers, nextUp, operatorActions, since, ...payload } = input;
    const shell = ctx.capabilities.shell;

    const today = new Date().toLocaleDateString("en-CH", { weekday: "long", year: "numeric", month: "long", day: "numeric" });

    // Build sections separately so we can split across Discord's 2000 char limit
    const sections: string[] = [];

    // Section 1: Header + summary + highlights
    const header: string[] = [];
    header.push(`**Metafactory Ecosystem Digest** — ${today}`);
    header.push("");
    header.push(summary);
    header.push("");
    if (highlights.length > 0) {
      header.push("**Highlights**");
      for (const h of highlights) {
        header.push(`> ${h}`);
      }
    }
    sections.push(header.join("\n"));

    // Section 2: Blockers + next up
    const status: string[] = [];
    if (blockers.length > 0) {
      status.push("**Needs attention**");
      for (const b of blockers) {
        status.push(`> ⚠️ ${b}`);
      }
      status.push("");
    }
    if (nextUp && nextUp.length > 0) {
      status.push("**Next up**");
      for (const n of nextUp) {
        status.push(`> → ${n}`);
      }
    }
    if (status.length > 0) sections.push(status.join("\n"));

    // Section 3: Operator actions
    const actions: string[] = [];
    if (operatorActions && operatorActions.length > 0) {
      actions.push("**Operator actions**");
      const priorityIcon = { high: "🔴", normal: "🔧", low: "💡" } as const;
      for (const a of operatorActions) {
        const icon = priorityIcon[a.priority] || "🔧";
        actions.push(`> ${icon} \`${a.command}\` — ${a.reason}`);
      }
      actions.push("");
      actions.push("_Generated by Pulse P_ECOSYSTEM_DIGEST_");
      sections.push(actions.join("\n"));
    } else {
      sections[sections.length - 1] += "\n\n_Generated by Pulse P_ECOSYSTEM_DIGEST_";
    }

    // Merge sections into messages that fit Discord's 2000 char limit
    const DISCORD_LIMIT = 1900; // Leave margin for encoding overhead
    const messages: string[] = [];
    let current = "";
    for (const section of sections) {
      if (current && (current.length + 2 + section.length) > DISCORD_LIMIT) {
        messages.push(current);
        current = section;
      } else {
        current = current ? current + "\n\n" + section : section;
      }
    }
    if (current) messages.push(current);

    const digest = sections.join("\n\n");

    // Post to Discord if shell is available and we have real content
    let posted = false;
    const hasContent = summary && summary !== "Unable to generate summary" && highlights.length > 0;
    if (shell && hasContent) {
      try {
        let allPosted = true;
        for (let i = 0; i < messages.length; i++) {
          // Write to temp file to avoid shell escaping issues with backticks, $, quotes, emoji
          const tmpFile = `/tmp/pulse-digest-${Date.now()}-${i}.txt`;
          await shell(`cat > '${tmpFile}' << 'PULSE_EOF'\n${messages[i]}\nPULSE_EOF`);
          const result = await shell(`bun ~/bin/discord post --channel general "$(cat '${tmpFile}')" && rm -f '${tmpFile}'`);
          if (result.code !== 0) {
            await shell(`rm -f '${tmpFile}'`);
            allPosted = false;
            break;
          }
        }
        posted = allPosted;
      } catch (_err) {
        // Discord posting is optional — don't fail the pipeline
        posted = false;
      }
    }

    return {
      ...payload,
      summary,
      highlights,
      blockers,
      nextUp,
      operatorActions,
      digest,
      posted,
      formattedAt: new Date().toISOString(),
    };
  },
};
